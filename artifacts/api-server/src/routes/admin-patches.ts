/**
 * POST /api/admin/realloc-full-team
 * One-time patch: reassigns all assets from "Full Team" to "Mobile 2".
 * Idempotent — safe to call multiple times (no-ops if already done).
 * Requires manager role.
 */
router.post("/realloc-full-team", requireAuth, async (req, res) => {
  const role = req.auth?.role;
  if (role !== "manager" && role !== "administrator") {
    res.status(403).json({ error: "Manager role required" });
    return;
  }

  const FULL_TEAM_ID = "5165dd26-95c0-45c9-a89a-82822c381427";
  const MOBILE2_ID   = "5456bd91-2512-47f9-9e77-82e44d0b06f6";

  try {
    const assetResult = await db.execute(sql`
      UPDATE assets
      SET team_id = ${MOBILE2_ID}
      WHERE team_id = ${FULL_TEAM_ID}
    `);
    const assetsUpdated = (assetResult as any).rowCount ?? 0;

    const jobResult = await db.execute(sql`
      UPDATE jobs
      SET team_id = ${MOBILE2_ID}
      WHERE team_id = ${FULL_TEAM_ID}
      AND status = 'pending'
    `);
    const jobsUpdated = (jobResult as any).rowCount ?? 0;

    // Null out any audit references (FK), then delete the team row
    await db.execute(sql`UPDATE audits SET team_id = NULL WHERE team_id = ${FULL_TEAM_ID}`);
    await db.execute(sql`DELETE FROM teams WHERE id = ${FULL_TEAM_ID}`);

    res.json({
      ok: true,
      assetsUpdated,
      jobsUpdated,
      message: `Reallocated ${assetsUpdated} assets and ${jobsUpdated} pending jobs from Full Team → Mobile 2; Full Team deleted`,
    });
  } catch (err: any) {
    console.error("[admin/realloc-full-team]", err);
    res.status(500).json({ error: err.message });
  }
});

